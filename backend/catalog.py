def seed_products(connection) -> None:
    connection.executemany(
        """INSERT OR IGNORE INTO products
           (id, name, category, price, unit, coverage, description, image, specs)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        [
            (
                product["id"],
                product["name"],
                product["category"],
                product["price"],
                product["unit"],
                product["coverage"],
                product["description"],
                product["image"],
                json.dumps(product["specs"], ensure_ascii=False),
            )
            for product in PRODUCTS
        ],
    )
